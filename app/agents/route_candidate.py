from agents import function_tool, RunContextWrapper

from app.schemas.agent_state import CandidateRoute, GeocoderAgentOutput, CandidateRouteAgentOutput, IntentOutput, RoutePlannerContext
from app.config import settings
import httpx

GOOGLE_ROUTES_URL = "https://routes.googleapis.com/directions/v2:computeRoutes"

@function_tool
async def fetch_candidate_routes_tool(ctx : RunContextWrapper[RoutePlannerContext]) -> CandidateRouteAgentOutput:
    """
    Fetches candidate routes based on the geocoded origin and destination.

    Args:
        ctx (RunContextWrapper[RoutePlannerContext]): The context containing the geocoder result and intent output.

    Returns:
        CandidateRouteAgentOutput: A list of candidate routes generated by the route candidate agent.
    """
    geocoder_result = ctx.context.geocoder_output
    intent_output = ctx.context.intent_output
    return await fetch_candidate_routes(geocoder_result, intent_output)

async def fetch_candidate_routes(geocoder_result : GeocoderAgentOutput, intent_output : IntentOutput) -> CandidateRouteAgentOutput:
    """
    Fetches candidate routes based on the geocoded origin and destination.

    Args:
        geocoder_result (GeocoderAgentOutput): The output from the geocoder agent containing origin and destination coordinates.

    Returns:
        CandidateRouteAgentOutput: A list of candidate routes generated by the route candidate agent.
    """

    route_modifiers = intent_output.routeModifiers
    async with httpx.AsyncClient(timeout=30.0) as client:
       headers = {
           "Content-Type": "application/json",
           "X-Goog-Api-Key": settings.GOOGLE_MAPS_API_KEY,
           "X-Goog-FieldMask": "routes.duration,routes.distanceMeters,routes.polyline.encodedPolyline"
       }

       body = {
            "origin" : {
                "location" : {
                    "latLng" : {
                        "latitude" : geocoder_result.origin.coordinates.lat,
                        "longitude" : geocoder_result.origin.coordinates.lng
                    }
                }
            },
            "destination" : {
                "location" : {
                    "latLng" : {
                        "latitude" : geocoder_result.destination.coordinates.lat,
                        "longitude" : geocoder_result.destination.coordinates.lng
                    }
                }
            },
            "travelMode" : intent_output.travel_mode.upper() if intent_output.travel_mode else "DRIVE",
            "computeAlternativeRoutes" : True,
            "routeModifiers" : intent_output.routeModifiers.model_dump(),
       }

       response = await client.post(GOOGLE_ROUTES_URL, headers=headers, json=body)
       response.raise_for_status()
       data = response.json()
    candidate_routes = []
    routes = data.get("routes", [])
    for index, route in enumerate(routes):
        route_id = f"route_{index + 1}"
        duration_seconds = int(route.get("duration", 0).replace("s", ""))
        duration_minutes = round(duration_seconds / 60)
        distance_metres = route.get("distanceMeters", None)
        polyline = route.get("polyline", {}).get("encodedPolyline", None)
        candidates_route = CandidateRoute(
            route_id=route_id,
            duration_minutes=duration_minutes,
            distance_metres=distance_metres,
            polyline=polyline
            )
        candidate_routes.append(candidates_route)
    
    # now we deduplicate the candidate routes
    seen = {}
    final_routes = []
    for route in candidate_routes:
        if route.polyline not in seen:
            seen[route.polyline] = route
        else:
            if route.duration_minutes < seen[route.polyline].duration_minutes:
                seen[route.polyline] = route
    final_routes = list(seen.values())
    final_response = CandidateRouteAgentOutput(candidate_routes=final_routes)
    return final_response





    



